"""Regenerate frontend/js/spread/model.js from the teammate's fire-spread simulator.

    python3 scripts/make_spread_model.py

The main simulator (frontend/lab.html) runs the 2D fire-spread physics of
blackfox/db/knowledge/habitat_fire_sim.html. This script copies that file's physics block - from the
"Knowledge-base references" marker to the "Rendering" marker - character for character into an ES module,
so the calculations stay exactly the teammate's. Only the small wrapper around it is written here.
tests/frontend/test_spread_model.py fails when the module and the teammate's file drift apart.
"""

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "blackfox" / "db" / "knowledge" / "habitat_fire_sim.html"
TARGET = ROOT / "frontend" / "js" / "spread" / "model.js"
START = "// ---------- Knowledge-base references ----------"
END = "// ---------- Rendering ----------"

# names the main simulator reads from the model (getters for the `let` variables, which change)
CONSTS = ("R MAT MKEYS GREC PRESETS NX NY DX N AIR FUEL WALL idx kind mat room ROOMS OPEN ITEMS isOpenCell SUP RET S "
          "state prog burnT igT extinct TH DQ SM phi ux uy bz T0 Ub pShift limit phiF hOpp Vcon Vopp Uopt speedAt UeffAt "
          "fluid build solveFlow applyFlowScale markWallAdj reset ignite addLog step roomTick WHY wallAdj").split()
LETS = "t running speed acc done igns firstIgn maxDist everIgn extMode notIgnited gHist log roomStat uScale uMax".split()


def physics_block(html: str) -> str:
    a, b = html.index(START), html.index(END)
    return html[a:b]


def module_text(block: str) -> str:
    getters = ",\n    ".join(f"get {n}() {{ return {n}; }}, set {n}(v) {{ {n} = v; }}" for n in LETS)
    return f"""// GENERATED by scripts/make_spread_model.py - do not edit by hand.
// The 2D fire-spread physics of the teammate's simulator (blackfox/db/knowledge/habitat_fire_sim.html),
// copied character for character between its "Knowledge-base references" and "Rendering" markers.
// Only this wrapper is new: it gives every page its own model and turns the original's UI calls into hooks.
export function createModel(hooks = {{}}) {{
  const renderLog = () => hooks.onLog?.();         // the original redraws its event list here
  const renderRooms = () => {{}};                   // ... and its room cards / sliders: the page does that
  const updateStatic = () => {{}};
  const syncPlay = () => hooks.onStop?.();          // called when the 30-minute run ends
// ======================= copied block starts =======================
{block}// ======================= copied block ends =========================
  return {{
    {", ".join(CONSTS)},
    {getters},
  }};
}}
"""


if __name__ == "__main__":
    TARGET.write_text(module_text(physics_block(SOURCE.read_text(encoding="utf-8"))), encoding="utf-8")
    print(f"wrote {TARGET.relative_to(ROOT)}")
